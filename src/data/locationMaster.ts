export function getCities() {
  return Array.from(new Set(locationMaster.map((item) => item.city))).sort();
}

export function getAreasByCity(city: string) {
  return locationMaster
    .filter((item) => item.city === city)
    .map((item) => item.area)
    .sort();
}

export function getCitiesByArea(area: string) {
  return Array.from(
    new Set(
      locationMaster
        .filter((item) => item.area.toLowerCase() === area.toLowerCase())
        .map((item) => item.city)
    )
  ).sort();
}

export function findLocation(city: string, area: string) {
  return locationMaster.find(
    (item) =>
      item.city.toLowerCase() === city.toLowerCase() &&
      item.area.toLowerCase() === area.toLowerCase()
  );
}
